function cleanPdfText(value) {
  return String(value ?? "")
    .replace(/[\u0000-\u001f\u007f]/g, " ")
    .replace(/[\u2010-\u2015]/g, "-")
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/\u2026/g, "...")
    .replace(/[^\u0020-\u00ff]/g, "?")
    .replace(/\s+/g, " ")
    .trim();
}

function escapePdf(value) {
  return cleanPdfText(value).replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

function rgb(color) {
  return `${color[0]} ${color[1]} ${color[2]}`;
}

function formatNumber(value) {
  if (value == null || !Number.isFinite(value)) return null;
  return new Intl.NumberFormat("en-US", { maximumFractionDigits: 1, notation: Math.abs(value) >= 100000 ? "compact" : "standard" }).format(value);
}

function wrap(value, width, fontSize) {
  const words = cleanPdfText(value).split(" ").filter(Boolean);
  const lines = [];
  let line = "";
  const max = Math.max(8, Math.floor(width / (fontSize * 0.52)));
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (next.length > max && line) {
      lines.push(line);
      line = word;
    } else {
      line = next;
    }
  }
  if (line) lines.push(line);
  return lines;
}

class Canvas {
  constructor(width, height, pageNumber, totalPages, copy, snapshot) {
    this.width = width;
    this.height = height;
    this.ops = [];
    this.copy = copy;
    this.snapshot = snapshot;
    this.pageNumber = pageNumber;
    this.totalPages = totalPages;
  }

  fill(color) { this.ops.push(`${rgb(color)} rg`); }
  stroke(color) { this.ops.push(`${rgb(color)} RG`); }
  rect(x, y, width, height, color, strokeColor = null, radius = 0) {
    this.fill(color);
    if (strokeColor) this.stroke(strokeColor);
    const op = `${x.toFixed(2)} ${y.toFixed(2)} ${width.toFixed(2)} ${height.toFixed(2)} re`;
    this.ops.push(`${op} ${strokeColor ? "B" : "f"}`);
  }
  line(x1, y1, x2, y2, color = COLORS.line, width = 1) {
    this.stroke(color);
    this.ops.push(`${width} w ${x1.toFixed(2)} ${y1.toFixed(2)} m ${x2.toFixed(2)} ${y2.toFixed(2)} l S`);
  }
  text(value, x, y, size = 10, options = {}) {
    const font = options.bold ? "F2" : "F1";
    this.fill(options.color || COLORS.ink);
    this.ops.push(`BT /${font} ${size} Tf ${x.toFixed(2)} ${y.toFixed(2)} Td (${escapePdf(value)}) Tj ET`);
  }
  paragraph(value, x, top, width, size = 10, options = {}) {
    const lineHeight = options.lineHeight || size * 1.42;
    const lines = wrap(value, width, size).slice(0, options.maxLines || 99);
    lines.forEach((line, index) => this.text(line, x, top - index * lineHeight, size, options));
    return top - lines.length * lineHeight;
  }
  header(kicker, title, subtitle) {
    this.text("EXPLORE", 42, this.height - 43, 11, { bold: true, color: COLORS.blue });
    this.text(kicker.toUpperCase(), 42, this.height - 76, 8, { bold: true, color: COLORS.muted });
    this.text(title, 42, this.height - 105, this.width > 700 ? 25 : 21, { bold: true });
    if (subtitle) this.paragraph(subtitle, 42, this.height - 127, this.width - 84, 9.5, { color: COLORS.muted, maxLines: 2 });
    this.line(42, this.height - 148, this.width - 42, this.height - 148, COLORS.line, 0.8);
  }
  footer() {
    this.line(42, 34, this.width - 42, 34, COLORS.line, 0.6);
    this.text(`${this.copy.fingerprint}: ${this.snapshot.fingerprint}`, 42, 19, 6.8, { color: COLORS.muted });
    this.text(`${this.pageNumber} / ${this.totalPages}`, this.width - 72, 19, 7, { color: COLORS.muted });
  }
  valueCard(x, y, width, label, value, delta = null, tone = COLORS.blue) {
    this.rect(x, y, width, 76, COLORS.faint);
    this.rect(x, y + 72, width, 4, tone);
    this.text(label.toUpperCase(), x + 14, y + 53, 7, { bold: true, color: COLORS.muted });
    this.text(value ?? this.copy.unavailable, x + 14, y + 25, value ? 20 : 12, { bold: true, color: value ? COLORS.ink : COLORS.muted });
    if (delta != null) this.text(`${delta >= 0 ? "+" : ""}${delta.toFixed(1)}%`, x + width - 55, y + 27, 8, { bold: true, color: delta >= 0 ? COLORS.green : COLORS.red });
  }
  bars(rows, x, y, width, height, valueKey = "count") {
    const values = rows.map((row) => Number(row[valueKey]) || 0);
    const max = Math.max(1, ...values);
    const gap = 7;
    const barH = Math.min(22, (height - gap * Math.max(0, rows.length - 1)) / Math.max(1, rows.length));
    rows.forEach((row, index) => {
      const rowY = y + height - (index + 1) * barH - index * gap;
      const barWidth = (Number(row[valueKey]) || 0) / max * (width - 150);
      this.text(row.label, x, rowY + 6, 8, { color: COLORS.muted });
      this.rect(x + 118, rowY, Math.max(2, barWidth), barH, index === 0 ? COLORS.blue : COLORS.cyan);
      this.text(formatNumber(row[valueKey]) || "-", x + 125 + barWidth, rowY + 6, 8, { bold: true });
    });
  }
  trend(points, x, y, width, height, key = "users") {
    const values = points.map((point) => Number(point[key]) || 0);
    if (values.length < 2 || Math.max(...values) === 0) {
      this.text(this.copy.noData, x, y + height / 2, 9, { color: COLORS.muted });
      return;
    }
    const max = Math.max(...values);
    this.line(x, y, x + width, y, COLORS.line, 0.7);
    this.line(x, y, x, y + height, COLORS.line, 0.7);
    this.stroke(COLORS.blue);
    const commands = values.map((value, index) => {
      const px = x + index / (values.length - 1) * width;
      const py = y + value / max * height;
      return `${px.toFixed(2)} ${py.toFixed(2)} ${index ? "l" : "m"}`;
    });
    this.ops.push(`2 w ${commands.join(" ")} S`);
  }
  toString() { return this.ops.join("\n"); }
}

function metricDelta(snapshot, key) {
  return snapshot.comparison?.deltas?.[key]?.percent ?? null;
}

