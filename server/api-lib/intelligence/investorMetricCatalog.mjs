const canonicalSource = "analytics_normalized_events via Business Analytics Core v3";
const behavioralContract = "analytics-ingestion-v2";

function metric({
  label,
  businessQuestion,
  definition,
  formula,
  unit,
  availability,
  identity = "not required",
  gaps,
  privacy = "aggregated behavioral data",
  comparison = true,
  source = canonicalSource,
  contract = behavioralContract,
  interpretation,
}) {
  return Object.freeze({
    label,
    business_question: businessQuestion,
    definition,
    formula,
    source,
    contract,
    unit,
    reporting_availability: availability,
    availability,
    instrumentation_start_date: null,
    reporting_period: "selected UTC reporting window",
    freshness: "data_as_of from the canonical snapshot",
    identity_requirements: identity,
    known_coverage_gaps: gaps,
    privacy_classification: privacy,
    privacy,
    export_eligibility: ["executive_business", "investor_safe"],
    comparison,
    interpretation,
  });
}

